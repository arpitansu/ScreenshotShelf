import Foundation
import AppKit
import CryptoKit
import UniformTypeIdentifiers
import ImageIO

struct ClipItem: Identifiable, Codable, Equatable {
    enum Kind: String, Codable { case text, image }

    let id: UUID
    var kind: Kind
    var text: String?       // for text clips
    var fileName: String?   // for image clips
    var createdAt: Date
    var pinned: Bool
    /// Copied on your iPhone or iPad and received through Universal Clipboard.
    /// Optional so history saved by older versions still loads.
    var fromOtherDevice: Bool?
    /// Fingerprint of an image's bytes, so the same image is never stored twice.
    var contentHash: String?

    var preview: String {
        guard let text else { return "Image" }
        let collapsed = text
            .replacingOccurrences(of: "\n", with: " ")
            .trimmingCharacters(in: .whitespacesAndNewlines)
        return String(collapsed.prefix(300))
    }
}

/// Clipboard history: remembers what you copy so you can copy it again later.
@MainActor
final class ClipStore: NSObject, ObservableObject {
    @Published private(set) var clips: [ClipItem] = []

    /// Also save images copied on your iPhone or iPad. Each one is transferred to the Mac
    /// as soon as it's copied, even if you never paste it. Remembered across restarts.
    @Published var saveRemoteImages: Bool {
        didSet { UserDefaults.standard.set(saveRemoteImages, forKey: "saveRemoteImages") }
    }

    /// While paused, nothing you copy is recorded. Remembered across restarts.
    @Published var isPaused: Bool {
        didSet { UserDefaults.standard.set(isPaused, forKey: "clipboardPaused") }
    }

    /// Used for the shared "Copied" toast.
    weak var toastHost: ShelfStore?

    static let maxClips = 200
    static let maxTextLength = 20_000
    /// Images bigger than this aren't kept (a full-screen Retina capture is ~5–10 MB).
    nonisolated static let maxImageBytes = 10 * 1024 * 1024
    /// At most this many copied images are kept, so history can't fill your disk
    /// (worst case about 30 × 10 MB = 300 MB, usually far less).
    static let maxImageClips = 30

    /// Pasteboard types that password managers and similar apps use to say "don't record this".
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword"
    ]

    /// Marks content that arrived from another Apple device (Universal Clipboard).
    private static let remoteType = "com.apple.is-remote-clipboard"

    private let folder: URL
    private let metadataURL: URL
    private var lastChangeCount: Int
    /// What the clipboard held the last time something was recorded (or pasted back by us).
    /// macOS sometimes says "the clipboard changed" when the content didn't, for example
    /// while a copy from your iPhone is on its way. Same content = nothing new to record.
    private var lastSignature: String?
    private var timer: Timer?
    /// Image formats an iPhone/iPad copy may offer, most compact first. A camera photo
    /// offered as PNG or TIFF can be 20–80 MB, so those are only a last resort.
    private static let imageTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("public.heic"),
        NSPasteboard.PasteboardType("public.heif"),
        NSPasteboard.PasteboardType("public.jpeg"),
        .png,
        .tiff
    ]

    /// Picks the best image format on offer, including any other image type the device sends.
    private static func bestImageType(in types: [NSPasteboard.PasteboardType]) -> NSPasteboard.PasteboardType? {
        if let preferred = imageTypes.first(where: { types.contains($0) }) { return preferred }
        return types.first { type in
            guard let uti = UTType(type.rawValue) else { return false }
            return uti.conforms(to: .image)
        }
    }

    /// Longest side, in pixels, for photos too large to keep as they are.
    nonisolated private static let downscaleMaxPixels = 3072
    /// Fetches images from your iPhone/iPad off the main thread, so the app never stalls.
    private let remoteQueue = DispatchQueue(label: "ScreenshotShelf.remoteClipboard", qos: .utility)
    private var fetchingRemoteImage = false
    private var saveTask: Task<Void, Never>?

    override init() {
        let fm = FileManager.default
        let support = fm.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("ScreenshotShelf", isDirectory: true)
        folder = support.appendingPathComponent("Clips", isDirectory: true)
        metadataURL = support.appendingPathComponent("clips.json")
        try? fm.createDirectory(at: folder, withIntermediateDirectories: true)
        lastChangeCount = NSPasteboard.general.changeCount
        isPaused = UserDefaults.standard.bool(forKey: "clipboardPaused")
        saveRemoteImages = (UserDefaults.standard.object(forKey: "saveRemoteImages") as? Bool) ?? true
        super.init()
        load()
        lastSignature = currentLocalSignature()
    }

    // MARK: - Watching

    func startWatching() {
        let timer = Timer(timeInterval: 0.5, target: self,
                          selector: #selector(poll), userInfo: nil, repeats: true)
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    @objc private func poll() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        // Paused: skip it entirely, and it won't be picked up after resuming either.
        if isPaused { return }
        if count == PasteboardTracker.ownChangeCount { return }

        let types = pb.types ?? []
        if types.contains(where: { Self.privateTypes.contains($0.rawValue) }) { return }
        let isRemote = types.contains(where: { $0.rawValue == Self.remoteType })

        // Photos copied on the iPhone often arrive as a file that Universal Clipboard saved
        // on this Mac, with only a link to it on the clipboard. Read the photo from that file.
        if let fileURL = universalClipboardImageFile(pb, types: types, isRemote: isRemote) {
            if saveRemoteImages { fetchRemoteImageFile(fileURL) }
            return
        }

        // Copied on your iPhone or iPad. The content is fetched from the device when read.
        if isRemote {
            let imageType = Self.bestImageType(in: types)
            if let imageType {
                // A photo or image (it may also carry a caption or link; the image wins).
                if saveRemoteImages { fetchRemoteImage(type: imageType) }
            } else if types.contains(.string),
                      let string = pb.string(forType: .string),
                      !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                // Text arrives almost instantly.
                recordText(String(string.prefix(Self.maxTextLength)), fromOtherDevice: true)
            }
            return
        }

        if types.contains(.fileURL) { return }   // files copied in Finder

        if let string = pb.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            recordText(String(string.prefix(Self.maxTextLength)), fromOtherDevice: false)
        } else if let png = pb.data(forType: .png) {
            recordImage(original: png, typeID: NSPasteboard.PasteboardType.png.rawValue, fromOtherDevice: false)
        } else if let tiff = pb.data(forType: .tiff) {
            recordImage(original: tiff, typeID: NSPasteboard.PasteboardType.tiff.rawValue, fromOtherDevice: false)
        }
    }

    /// The image file Universal Clipboard saved for a copy made on your iPhone/iPad, if that's
    /// what's on the clipboard. Files you copy in Finder don't qualify (they're not in
    /// Universal Clipboard's own folder and aren't marked as coming from another device).
    private func universalClipboardImageFile(_ pb: NSPasteboard,
                                             types: [NSPasteboard.PasteboardType],
                                             isRemote: Bool) -> URL? {
        guard types.contains(.fileURL),
              let urls = pb.readObjects(forClasses: [NSURL.self],
                                        options: [.urlReadingFileURLsOnly: true]) as? [URL],
              urls.count == 1,
              let url = urls.first else { return nil }
        let path = url.path
        let fromUniversalClipboard = isRemote
            || path.contains("/shared-pasteboard/")
            || path.contains("group.com.apple.coreservices.useractivityd")
        guard fromUniversalClipboard,
              let type = UTType(filenameExtension: url.pathExtension),
              type.conforms(to: .image) else { return nil }
        return url
    }

    /// Reads a photo Universal Clipboard saved as a file, in the background, shrinking it
    /// if it's too large to keep, then records it on the main thread.
    private func fetchRemoteImageFile(_ url: URL) {
        guard !fetchingRemoteImage else { return }
        fetchingRemoteImage = true
        let typeID = UTType(filenameExtension: url.pathExtension)?.identifier ?? UTType.jpeg.identifier
        remoteQueue.async { [weak self] in
            let result: (data: Data, typeID: String)? = autoreleasepool {
                guard let data = try? Data(contentsOf: url, options: .mappedIfSafe) else { return nil }
                if data.count <= ClipStore.maxImageBytes { return (data, typeID) }
                guard let smaller = ClipStore.downscaledJPEG(data) else { return nil }
                return (smaller, UTType.jpeg.identifier)
            }
            Task { @MainActor in
                guard let self else { return }
                self.fetchingRemoteImage = false
                guard !self.isPaused else { return }
                guard let result else {
                    self.toastHost?.showToast("Couldn't save the image from your iPhone")
                    return
                }
                self.recordImage(original: result.data, typeID: result.typeID, fromOtherDevice: true)
            }
        }
    }

    /// Pulls an image over from the iPhone/iPad in the background (this can take a
    /// second or two for a photo), then records it back on the main thread.
    private func fetchRemoteImage(type: NSPasteboard.PasteboardType) {
        guard !fetchingRemoteImage else { return }   // one transfer at a time
        fetchingRemoteImage = true
        let typeID = type.rawValue
        remoteQueue.async { [weak self] in
            // Fetch from the phone, and shrink it here (off the main thread) if it's too big to keep.
            let result: (data: Data, typeID: String)? = autoreleasepool {
                guard let data = NSPasteboard.general.data(forType: NSPasteboard.PasteboardType(typeID)) else {
                    return nil
                }
                if data.count <= ClipStore.maxImageBytes { return (data, typeID) }
                guard let smaller = ClipStore.downscaledJPEG(data) else { return nil }
                return (smaller, UTType.jpeg.identifier)
            }
            Task { @MainActor in
                guard let self else { return }
                self.fetchingRemoteImage = false
                guard !self.isPaused else { return }
                guard let result else {
                    self.toastHost?.showToast("Couldn't save the image from your iPhone")
                    return
                }
                self.recordImage(original: result.data, typeID: result.typeID, fromOtherDevice: true)
            }
        }
    }

    /// Re-encodes a very large photo as a JPEG at most `downscaleMaxPixels` on its longest side.
    /// Safe to call from any thread.
    nonisolated private static func downscaledJPEG(_ data: Data) -> Data? {
        let sourceOptions = [kCGImageSourceShouldCache: false] as CFDictionary
        guard let source = CGImageSourceCreateWithData(data as CFData, sourceOptions) else { return nil }
        let thumbOptions: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceThumbnailMaxPixelSize: downscaleMaxPixels,
            kCGImageSourceCreateThumbnailWithTransform: true
        ]
        guard let image = CGImageSourceCreateThumbnailAtIndex(source, 0, thumbOptions as CFDictionary) else {
            return nil
        }
        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(
            output, UTType.jpeg.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(destination, image,
                                   [kCGImageDestinationLossyCompressionQuality: 0.85] as CFDictionary)
        guard CGImageDestinationFinalize(destination) else { return nil }
        return output as Data
    }

    // MARK: - Recording (only genuinely new content)

    /// Fingerprint of what's on the clipboard right now, so whatever was already there
    /// when the app started isn't recorded again. Skips iPhone content (reading it
    /// would fetch it from the phone).
    private func currentLocalSignature() -> String? {
        let pb = NSPasteboard.general
        let types = pb.types ?? []
        if types.contains(where: { $0.rawValue == Self.remoteType }) { return nil }
        if let string = pb.string(forType: .string) {
            return "t:" + String(string.prefix(Self.maxTextLength))
        }
        if let data = pb.data(forType: .png) ?? pb.data(forType: .tiff) {
            return "i:" + Self.fingerprint(data)
        }
        return nil
    }

    private static func fingerprint(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    private func recordText(_ text: String, fromOtherDevice: Bool) {
        let signature = "t:" + text
        guard signature != lastSignature else { return }   // same as before: not a new copy
        lastSignature = signature
        addText(text, fromOtherDevice: fromOtherDevice)
    }

    private func recordImage(original: Data, typeID: String, fromOtherDevice: Bool) {
        guard original.count <= Self.maxImageBytes * 4 else { return }   // absurdly large: skip
        let hash = Self.fingerprint(original)
        let signature = "i:" + hash
        guard signature != lastSignature else { return }   // same image still on the clipboard
        lastSignature = signature

        // Already in history: move it to the top instead of storing a duplicate.
        if let i = clips.firstIndex(where: { $0.kind == .image && $0.contentHash == hash }) {
            var existing = clips.remove(at: i)
            existing.createdAt = Date()
            clips.insert(existing, at: 0)
            save()
            return
        }

        // TIFF (what many Mac apps put on the clipboard) is huge, so it's stored as PNG.
        // PNG, HEIC and JPEG (typical from an iPhone) are stored exactly as they came.
        if typeID == NSPasteboard.PasteboardType.tiff.rawValue {
            let png: Data? = autoreleasepool {
                NSBitmapImageRep(data: original)?.representation(using: .png, properties: [:])
            }
            if let png { addImage(data: png, fileExtension: "png", hash: hash, fromOtherDevice: fromOtherDevice) }
        } else {
            let ext = UTType(typeID)?.preferredFilenameExtension ?? "png"
            addImage(data: original, fileExtension: ext, hash: hash, fromOtherDevice: fromOtherDevice)
        }
    }

    private func addText(_ text: String, fromOtherDevice: Bool = false) {
        if let i = clips.firstIndex(where: { $0.kind == .text && $0.text == text }) {
            var existing = clips.remove(at: i)
            existing.createdAt = Date()
            clips.insert(existing, at: 0)
        } else {
            clips.insert(ClipItem(id: UUID(), kind: .text, text: text, fileName: nil,
                                  createdAt: Date(), pinned: false,
                                  fromOtherDevice: fromOtherDevice ? true : nil,
                                  contentHash: nil), at: 0)
        }
        trimOverflow()
        save()
    }

    private func addImage(data: Data, fileExtension: String, hash: String, fromOtherDevice: Bool) {
        guard data.count <= Self.maxImageBytes else { return }
        let id = UUID()
        let name = "\(id.uuidString).\(fileExtension)"
        do {
            try data.write(to: folder.appendingPathComponent(name), options: .atomic)
        } catch {
            return
        }
        clips.insert(ClipItem(id: id, kind: .image, text: nil, fileName: name,
                              createdAt: Date(), pinned: false,
                              fromOtherDevice: fromOtherDevice ? true : nil,
                              contentHash: hash), at: 0)
        trimOverflow()
        save()
    }

    // MARK: - Lookups

    func search(_ query: String) -> [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces)
        guard !q.isEmpty else { return clips }
        return clips.filter { ($0.text ?? "").localizedCaseInsensitiveContains(q) }
    }

    func fileURL(for clip: ClipItem) -> URL? {
        // Only ever plain file names inside the app's own Clips folder.
        guard let name = clip.fileName,
              !name.isEmpty, !name.contains("/"), !name.hasPrefix(".") else { return nil }
        return folder.appendingPathComponent(name)
    }

    func thumbnail(for clip: ClipItem) -> NSImage? {
        guard let url = fileURL(for: clip) else { return nil }
        return ThumbnailCache.shared.image(for: url, maxPixelSize: 200)
    }

    // MARK: - Actions

    /// Puts the clip back on the clipboard, ready for ⌘V.
    func copy(_ clip: ClipItem) {
        let pb = NSPasteboard.general
        switch clip.kind {
        case .text:
            guard let text = clip.text else { return }
            pb.clearContents()
            pb.setString(text, forType: .string)
        case .image:
            guard let url = fileURL(for: clip), let data = try? Data(contentsOf: url) else { return }
            pb.clearContents()
            if url.pathExtension.lowercased() == "png" {
                pb.setData(data, forType: .png)
            } else {
                // HEIC/JPEG from an iPhone: offer a standard image every app accepts,
                // plus the original file format for apps that prefer it.
                if let image = NSImage(data: data) { pb.writeObjects([image]) }
                if let uti = UTType(filenameExtension: url.pathExtension)?.identifier {
                    pb.setData(data, forType: NSPasteboard.PasteboardType(uti))
                }
            }
        }
        PasteboardTracker.markOwnWrite()
        lastChangeCount = pb.changeCount
        switch clip.kind {
        case .text: lastSignature = clip.text.map { "t:" + $0 }
        case .image: lastSignature = clip.contentHash.map { "i:" + $0 }
        }

        if let i = clips.firstIndex(where: { $0.id == clip.id }) {
            var moved = clips.remove(at: i)
            moved.createdAt = Date()
            clips.insert(moved, at: 0)
            save()
        }
        toastHost?.showToast("Copied. Press ⌘V to paste")
    }

    func togglePin(_ clip: ClipItem) {
        guard let i = clips.firstIndex(where: { $0.id == clip.id }) else { return }
        clips[i].pinned.toggle()
        save()
    }

    func delete(_ clip: ClipItem) {
        removeFile(of: clip)
        clips.removeAll { $0.id == clip.id }
        save()
    }

    func clearUnpinned() {
        for clip in clips where !clip.pinned { removeFile(of: clip) }
        clips.removeAll { !$0.pinned }
        save()
    }

    func cleanupExpired(retentionDays: Int) {
        let cutoff = Date().addingTimeInterval(-Double(retentionDays) * 86_400)
        let expired = clips.filter { !$0.pinned && $0.createdAt < cutoff }
        guard !expired.isEmpty else { return }
        for clip in expired { removeFile(of: clip) }
        let ids = Set(expired.map(\.id))
        clips.removeAll { ids.contains($0.id) }
        save()
    }

    private func trimOverflow() {
        // Too many entries overall: drop the oldest unpinned ones.
        while clips.count > Self.maxClips,
              let last = clips.lastIndex(where: { !$0.pinned }) {
            removeFile(of: clips[last])
            clips.remove(at: last)
        }
        // Too many images: drop the oldest unpinned images.
        while clips.filter({ $0.kind == .image }).count > Self.maxImageClips,
              let last = clips.lastIndex(where: { $0.kind == .image && !$0.pinned }) {
            removeFile(of: clips[last])
            clips.remove(at: last)
        }
    }

    /// Clip images are the app's own copies (not your files), so they're removed outright.
    private func removeFile(of clip: ClipItem) {
        guard let url = fileURL(for: clip) else { return }
        ThumbnailCache.shared.remove(url)
        try? FileManager.default.removeItem(at: url)
    }

    // MARK: - Persistence

    private func load() {
        guard let data = try? Data(contentsOf: metadataURL) else { return }
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        guard let saved = try? decoder.decode([ClipItem].self, from: data) else { return }
        clips = saved.filter { clip in
            guard let url = fileURL(for: clip) else { return true }
            return FileManager.default.fileExists(atPath: url.path)
        }
    }

    /// Batches disk writes: many quick copies cause one write, not one each.
    private func save() {
        saveTask?.cancel()
        saveTask = Task {
            try? await Task.sleep(nanoseconds: 1_500_000_000)
            if !Task.isCancelled { self.saveNow() }
        }
    }

    /// Writes history to disk immediately (also called when the app quits).
    func saveNow() {
        saveTask?.cancel()
        saveTask = nil
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        if let data = try? encoder.encode(clips) {
            try? data.write(to: metadataURL, options: .atomic)
        }
    }
}
